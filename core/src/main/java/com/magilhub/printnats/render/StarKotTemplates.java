    /**
     * Template 5 (KOT) — same layout/logic as {@link #printStarKotT3}, with the same
     * DB-driven font size + case customization PrintUtil's Template 2/5 has (see
     * KotText.getAsyncKotPrinterT2/T5): uiFeatureFlags.kotItemFontSize
     * (small|medium|medium2|big|sizeN, default small, mapped to a Star appendMultiple
     * width/height pair via KotText.starSizeMultiple) and kotItemTextCase
     * (title|upper|lower, default title, via KotText.applyItemCase) applied everywhere
     * PrintUtil's buildKotLines applies it: badges, table/guest info, order note, batch
     * note, items/modifiers/comments, and footer lines. Header, top divider, server name,
     * date/time line, and Guests: stay fixed/normal, matching buildKotLines' "static"
     * set. Only items/modifiers/comments get the new title|upper|lower case option —
     * other DB-sized text (order-source badge, order note, batch note) keeps the legacy
     * upper-or-as-received behavior (KotText.caseText), same distinction buildKotLines
     * makes between applyItemCase and caseText.
     */
    /** Apply the DB-driven Star size to `text` and print it, using the combined
     *  appendMultiple(bytes, width, height) form — size and text in ONE call — rather
     *  than the separate appendMultiple(w,h) + append(bytes)/appendInvert(bytes) pattern.
     *  Confirmed on-device (test print, sizes 6/7/8) that the separate-call pattern caps
     *  out at 2x2 on this printer even when a bigger multiple is requested, while this
     *  combined form already works at 3x3/4x4 elsewhere in this file (printStarReceipt
     *  line ~168, printStarKot line ~392). Also applies the size-driven bold (size2/
     *  size4, and everything >= SIZE_MEDIUM2 per the 2x2-ceiling finding — see
     *  t5SizeBold) and, when invert=true, wraps the text in invert mode, turned back off
     *  immediately after so it never bleeds into the next line (same discipline this file
     *  already uses for appendEmphasis). */
    private static void appendT5Sized(StarSink builder, byte[] text, int[] mult, boolean bold, boolean invert) {
        if (bold) {
            builder.appendEmphasis(true);
        }
        if (invert) {
            builder.appendInvert(true);
        }
        builder.appendMultiple(text, mult[0], mult[1]);
        if (invert) {
            builder.appendInvert(false);
        }
    }

