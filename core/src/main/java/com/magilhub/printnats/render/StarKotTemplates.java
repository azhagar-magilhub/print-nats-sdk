        int[] t5Mult = KotText.starSizeMultiple(t5SizeCode);
        // size2/size4 are the "+bold" entries on the ladder (see KotText.t4SizeBytes) —
        // same width/height as size1/size3 but bold, so they need to look different from
        // their non-bold counterparts instead of collapsing to identical Star output.
        //
        // Confirmed on a real device (test print, sizes 6/7/8 side by side): this Star
        // printer/SDK caps appendMultiple's actual rendered magnification at 2x2 — sizes
        // 8-12 request 3x3 through 6x6 but the hardware silently clamps them all down to
        // 2x2, so they printed visually identical to 6/7. There is no SDK-level way past
        // this (checked: StarSink only offers FontStyleType A/B — a font-table
        // swap, not a size increase — plus the multiplier that's already capped). Bold is
        // the only remaining dimension, so every size at/above the ceiling (>= SIZE_MEDIUM2)
        // goes bold too — giving two distinguishable tiers (plain 2x2, bold 2x2) instead of
