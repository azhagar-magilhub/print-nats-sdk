            class Utils {
                int byteLength(String s) {
                    if (s == null) return 0;
                    try {
                        return s.getBytes(encoding.name()).length;
                    } catch (Exception e) { return s.length(); }
                }

                // left and right aligned on same printable lineWidth (measured in bytes)
                String leftRightAlign(String left, String right, int lineWidth) {
                    if (left == null) left = "";
                    if (right == null) right = "";

                    // trim newlines
                    left = left.replace("\n","").trim();
                    right = right.replace("\n","").trim();

                    int leftLen = byteLength(left);
                    int rightLen = byteLength(right);

                    // If too long, truncate right first then left
                    if (leftLen + rightLen > lineWidth) {
                        // allocate half to each as fallback
                        int half = Math.max(1, lineWidth / 2);
                        if (leftLen > half) {
                            left = safeTruncate(left, half);
                            leftLen = byteLength(left);
                        }
                        if (leftLen + rightLen > lineWidth && rightLen > half) {
                            right = safeTruncate(right, half);
                            rightLen = byteLength(right);
                        }
                    }

                    int spaces = lineWidth - (leftLen + rightLen);
                    if (spaces < 1) spaces = 1;

                    StringBuilder sb = new StringBuilder();
                    sb.append(left);
                    for (int i = 0; i < spaces; i++) sb.append(' ');
                    sb.append(right);
                    return sb.toString();
                }

                // truncate a string to fit 'targetBytes' bytes in the chosen encoding
                String safeTruncate(String s, int targetBytes) {
                    if (s == null) return "";
                    try {
                        byte[] bytes = s.getBytes(encoding.name());
                        if (bytes.length <= targetBytes) return s;
                        // build progressively to avoid breaking multi-byte chars
                        StringBuilder out = new StringBuilder();
                        for (int i = 0; i < s.length(); i++) {
                            out.append(s.charAt(i));
                            if (out.toString().getBytes(encoding.name()).length >= targetBytes) break;
                        }
                        return out.toString();
                    } catch (Exception e) {
                        // fallback to char truncation
                        return s.substring(0, Math.min(s.length(), targetBytes));
                    }
                }
            }
            Utils u = new Utils();

            String dashedLine = String.valueOf(new char[lineWidth]).replace("\0", "-");
            String equalDashLine = String.valueOf(new char[lineWidth]).replace("\0", "=");
            String station = isStation ?  stationName+" KOT"  : "Master KOT";
